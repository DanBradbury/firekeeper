#!/bin/sh
# Writes THIRD_PARTY_NOTICES.md: the license texts of every module linked into
# the firekeeper binary, plus the Go toolchain's own. Run it after changing
# go.mod (just notices). Needs the module cache: go mod download.
set -eu
cd "$(dirname "$0")/.."
out=THIRD_PARTY_NOTICES.md

# Modules linked into the binary on each platform Firekeeper builds for.
mods=$(for os in darwin linux windows; do
	GOOS=$os go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' .
done | sort -u)

{
	echo '# Third-party notices'
	echo
	# The single-quoted backticks below are Markdown code spans, not command
	# substitutions, so SC2016 does not apply.
	# shellcheck disable=SC2016
	echo 'Firekeeper is licensed under the Apache License 2.0 (see `LICENSE`). Binaries'
	echo 'built from this repository also contain the software'
	echo 'below, each under its own license. The full license texts follow.'
	echo
	echo '<!-- Generated by scripts/third-party-notices.sh. Do not edit by hand. -->'
	echo
	echo '| Component | Version |'
	echo '| --- | --- |'
	echo "| Go standard library and runtime | $(go env GOVERSION) |"
	echo "$mods" | while read -r path version dir; do echo "| $path | $version |"; done
	echo '| @lobehub/icons-static-svg (logo marks in the embedded icon font) | 1.101.0 |'
	echo
	echo '---'
	echo
	echo '## Go standard library and runtime'
	echo
	for f in LICENSE PATENTS; do
		echo '```text'
		cat "$(go env GOROOT)/$f"
		echo '```'
		echo
	done
	echo "$mods" | while read -r path version dir; do
		echo "## $path $version"
		echo
		files=$(cd "$dir" && for f in *; do printf '%s\n' "$f"; done |
			awk 'tolower($0) ~ /^(licen[cs]e|copying|notice|patents)/ &&
				$0 != "LICENSE-LOGO" && $0 != "LICENSE-SQLITE_VEC"')
		if [ -z "$files" ]; then
			case $path in
			github.com/mattn/go-localereader)
				echo 'This module ships no license file. Its README states: "License: MIT",'
				echo 'author Yasuhiro Matsumoto (a.k.a. mattn). The MIT License text appears'
				echo 'above under other modules.'
				echo
				continue
				;;
			*)
				echo "third-party-notices: no license file for $path" >&2
				exit 1
				;;
			esac
		fi
		for f in $files; do
			[ "$(echo "$files" | wc -l)" -gt 1 ] && echo "### $f" && echo
			echo '```text'
			cat "$dir/$f"
			# Keep the fence on its own line when a file lacks a final newline.
			[ -n "$(tail -c 1 "$dir/$f")" ] && echo
			echo '```'
			echo
		done
	done
	# Not a Go module: the logo SVGs built into internal/iconfont's embedded
	# font. The license text is kept, with the version, in the font's notice.
	echo '## @lobehub/icons-static-svg 1.101.0'
	echo
	# shellcheck disable=SC2016
	echo 'The logo marks in the embedded icon font (`internal/iconfont`) come from'
	echo 'this package. The marks are trademarks of their owners; see NOTICE.'
	echo
	notice=scripts/icon-font/NOTICE.md
	license=$(awk '/^```text$/{on=1} on{print} on&&/^```$/{exit}' "$notice")
	if [ -z "$license" ]; then
		echo "third-party-notices: no license block in $notice" >&2
		exit 1
	fi
	echo "$license"
} >"$out"
echo "wrote $out"
